import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'

const mocks = vi.hoisted(() => ({
  getUser: vi.fn(),
  upload: vi.fn(),
  remove: vi.fn(),
  getPublicUrl: vi.fn(),
}))

vi.mock('@/services/supabase', () => ({
  supabase: {
    auth: { getUser: mocks.getUser },
    storage: {
      from: vi.fn(() => ({
        upload: mocks.upload,
        remove: mocks.remove,
        getPublicUrl: mocks.getPublicUrl,
      })),
    },
  },
}))

import { deleteRideImage, getRideImageUrl, uploadRideImage } from './rideImageService'

function imageOf(type = 'image/png', size = 1024): File {
  const file = new File(['contenido'], 'portada.jpg', { type })
  Object.defineProperty(file, 'size', { value: size })

  return file
}

function authenticatedAs(id: string): void {
  mocks.getUser.mockResolvedValue({ data: { user: { id } }, error: null })
}

describe('rideImageService', () => {
  beforeEach(() => {
    vi.clearAllMocks()
    vi.spyOn(crypto, 'randomUUID').mockReturnValue('00000000-0000-4000-8000-000000000000')
    authenticatedAs('user-1')
    mocks.upload.mockResolvedValue({ data: { path: 'x' }, error: null })
    mocks.remove.mockResolvedValue({ data: null, error: null })
    mocks.getPublicUrl.mockReturnValue({
      data: {
        publicUrl:
          'https://cdn.example/ride-images/user-1/00000000-0000-4000-8000-000000000000.png',
      },
    })
  })

  afterEach(() => {
    vi.restoreAllMocks()
  })

  describe('uploadRideImage', () => {
    it('uploads the file under the user folder with a generated uuid', async () => {
      await expect(uploadRideImage(imageOf())).resolves.toBe(
        'user-1/00000000-0000-4000-8000-000000000000.png',
      )

      expect(mocks.upload).toHaveBeenCalledWith(
        'user-1/00000000-0000-4000-8000-000000000000.png',
        expect.any(File),
        {
          cacheControl: '3600',
          contentType: 'image/png',
          upsert: false,
        },
      )
    })

    it('rejects invalid files before touching auth or storage', async () => {
      await expect(uploadRideImage(imageOf('image/gif'))).rejects.toThrow(
        'Selecciona una imagen JPEG, PNG, WebP o AVIF.',
      )
      expect(mocks.getUser).not.toHaveBeenCalled()
      expect(mocks.upload).not.toHaveBeenCalled()
    })

    it('requires an authenticated user', async () => {
      mocks.getUser.mockResolvedValue({ data: { user: null }, error: null })

      await expect(uploadRideImage(imageOf())).rejects.toThrow(
        'Debes iniciar sesión para subir una imagen.',
      )
      expect(mocks.upload).not.toHaveBeenCalled()
    })

    it('requires an authenticated user when reading the session fails', async () => {
      mocks.getUser.mockResolvedValue({ data: { user: null }, error: new Error('offline') })

      await expect(uploadRideImage(imageOf())).rejects.toThrow(
        'Debes iniciar sesión para subir una imagen.',
      )
    })

    it('maps a storage failure to a user-facing message', async () => {
      mocks.upload.mockResolvedValue({ data: null, error: new Error('quota') })

      await expect(uploadRideImage(imageOf())).rejects.toThrow('No se ha podido subir la imagen.')
    })
  })

  describe('deleteRideImage', () => {
    it('removes the given path from the ride-images bucket', async () => {
      await deleteRideImage('user-1/00000000-0000-4000-8000-000000000000.png')

      expect(mocks.remove).toHaveBeenCalledWith(['user-1/00000000-0000-4000-8000-000000000000.png'])
    })

    it('maps a storage failure to a user-facing message', async () => {
      mocks.remove.mockResolvedValue({ data: null, error: new Error('missing') })

      await expect(
        deleteRideImage('user-1/00000000-0000-4000-8000-000000000000.png'),
      ).rejects.toThrow('No se ha podido eliminar la imagen.')
    })
  })

  describe('getRideImageUrl', () => {
    it('returns the public url generated by storage', () => {
      expect(getRideImageUrl('user-1/00000000-0000-4000-8000-000000000000.png')).toBe(
        'https://cdn.example/ride-images/user-1/00000000-0000-4000-8000-000000000000.png',
      )
      expect(mocks.getPublicUrl).toHaveBeenCalledWith(
        'user-1/00000000-0000-4000-8000-000000000000.png',
      )
    })
  })
})
